import { ImapFlow } from "imapflow";
import { simpleParser } from "mailparser";
import { processInboundEmail } from "./inbound-handler";
import Sentry from "./sentry";

let syncInterval: Timer | null = null;
let imapClient: ImapFlow | null = null;
let lastKnownUid = 0;
let isSyncing = false;

export async function startGmailSync(): Promise<void> {
  const user = process.env.SMTP_USER;
  const pass = process.env.SMTP_PASS;

  if (!user || !pass) {
    console.log("[Gmail Sync] SMTP_USER or SMTP_PASS not set. Gmail inbox sync disabled.");
    return;
  }

  const createClient = () =>
    new ImapFlow({
      host: "imap.gmail.com",
      port: 993,
      secure: true,
      auth: { user, pass },
      logger: false,
      emitLogs: false,
    });

  imapClient = createClient();

  const syncCheck = async () => {
    if (isSyncing) return;
    isSyncing = true;

    try {
      if (!imapClient || !imapClient.usable) {
        try {
          if (imapClient) {
            await imapClient.logout().catch(() => {});
          }
        } catch {}
        imapClient = createClient();
        await imapClient.connect();
      }

      const lock = await imapClient.getMailboxLock("INBOX");
      try {
        const status = await imapClient.status("INBOX", { uidNext: true });
        if (!status) return;
        const currentUidNext = status.uidNext ?? 1;

        if (currentUidNext > lastKnownUid + 1) {
          const fetchRange = `${lastKnownUid + 1}:*`;
          for await (const msg of imapClient.fetch(
            fetchRange,
            { envelope: true, source: true, uid: true },
            { uid: true }
          )) {
            if (msg.uid <= lastKnownUid) continue;

            const fromAddress = msg.envelope?.from?.[0];
            const fromEmail = fromAddress?.address || "";
            const fromName = fromAddress?.name || fromEmail;
            const subject = msg.envelope?.subject || "(No Subject)";

            // Parse body
            let body = "";
            let bodyHtml: string | undefined;

            if (msg.source) {
              const parsed = await simpleParser(msg.source);
              body = (parsed.text || "").trim();
              if (typeof parsed.html === "string") {
                bodyHtml = parsed.html;
              }
            }

            // Prevent loops: skip outbound emails generated by Helpdesk itself
            const myEmail = user.toLowerCase();
            const isSelf = fromEmail.toLowerCase() === myEmail;
            const isHelpdeskSender =
              fromName.toLowerCase().includes("helpdesk support") ||
              subject.toLowerCase().startsWith("[gmail] email sent");

            if (isSelf && isHelpdeskSender) {
              console.log(`[Gmail Sync] Skipping self-outbound notification: "${subject}"`);
              lastKnownUid = Math.max(lastKnownUid, msg.uid);
              continue;
            }

            if (fromEmail) {
              console.log(`[Gmail Sync] Incoming email from "${fromEmail}" - Subject: "${subject}"`);
              await processInboundEmail({
                from: fromEmail,
                fromName,
                subject,
                body: body || (bodyHtml ? "HTML Email (view HTML tab)" : "(Empty message)"),
                bodyHtml,
              });
            }

            lastKnownUid = Math.max(lastKnownUid, msg.uid);
          }
        }
      } finally {
        lock.release();
      }
    } catch (err: any) {
      Sentry.captureException(err, { tags: { service: "gmail-sync", phase: "poll" } });
      console.warn(`[Gmail Sync] Check warning: ${err?.message || err}`);
    } finally {
      isSyncing = false;
    }
  };

  try {
    await imapClient.connect();
    const lock = await imapClient.getMailboxLock("INBOX");
    try {
      const status = await imapClient.status("INBOX", { uidNext: true });
      lastKnownUid = status ? (status.uidNext ?? 1) - 1 : 0;
      console.log(
        `[Gmail Sync] Connected to imap.gmail.com as ${user}. Monitoring INBOX for incoming emails (lastKnownUid: ${lastKnownUid}).`
      );
    } finally {
      lock.release();
    }

    // Check periodically every 15 seconds
    syncInterval = setInterval(syncCheck, 15000);
  } catch (err) {
    Sentry.captureException(err, { tags: { service: "gmail-sync", phase: "init" } });
    console.error("[Gmail Sync] Initial connection failed:", err);
    syncInterval = setInterval(syncCheck, 15000);
  }
}

export async function stopGmailSync(): Promise<void> {
  if (syncInterval) {
    clearInterval(syncInterval);
    syncInterval = null;
  }
  if (imapClient && imapClient.usable) {
    try {
      await imapClient.logout();
    } catch {}
    imapClient = null;
  }
}
